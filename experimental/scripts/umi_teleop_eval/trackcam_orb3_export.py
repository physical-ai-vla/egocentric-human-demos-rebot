"""Trackcam recording -> ORB-SLAM3 Mono-Inertial input (EuRoC layout + settings), fisheye kept as KannalaBrandt8 (2026-10-15).
  <rec>/orb3/<variant>/mav0/cam0/data/<t_ns>.png   grayscale as saved (960x540 for --save-scale 2), NO rectification
  <rec>/orb3/<variant>/mav0/imu0/data.csv          IMU device clock -> host, + offset_ms -> camera clock (trackcam_imu_v001)
  <rec>/orb3/<variant>/times.txt                    image timestamps (ns), ORB-SLAM3 EuRoC example format
  <rec>/orb3/<variant>/settings.yaml               KB4 /scale, IMU.T_b_c1 = T_imu_cam (R_CI from trackcam_imu_v001, lever from board_lever.json),
                                                   noise from camera_imu_right_v002 inflated (x NOISE_X densities, x WALK_X random walks)
variant 'sm' paints the self-view mask (UMI parts that move with the camera; selfview_mask.npy of the reference take) mid-grey.
    python scripts/trackcam_orb3_export.py datasets/trackcam_imu/<ts> [--variant raw|sm] [--mask-from <rec>] [--lever-from <rec>]"""
from __future__ import annotations
import argparse, json, shutil
from pathlib import Path
import cv2
import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
import sys; sys.path.insert(0, str(ROOT))
from handumi_collector.pose.timing import fit_device_to_host   # noqa: E402
NOISE_X, WALK_X = 5.0, 10.0


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("rec"); ap.add_argument("--variant", default="raw", choices=("raw", "sm"))
    ap.add_argument("--mask-from", default="datasets/trackcam_imu/20261015_205926"); ap.add_argument("--lever-from", default="datasets/trackcam_imu/20261015_205926")
    ap.add_argument("--n-features", type=int, default=1250); a = ap.parse_args()
    E = Path(a.rec); out = E / "orb3" / a.variant; shutil.rmtree(out, ignore_errors=True); (out / "mav0/cam0/data").mkdir(parents=True); (out / "mav0/imu0").mkdir(parents=True)
    sc = json.loads((E / "meta.json").read_text())["save_scale"]
    mask = np.load(ROOT / a.mask_from / "selfview_mask.npy") if a.variant == "sm" else None
    t_cam = np.load(E / "tracking_cam_t_ns.npy"); cap = cv2.VideoCapture(str(E / "tracking_cam.mp4")); k = 0; rows = []
    while k < len(t_cam):
        ok, f = cap.read()
        if not ok: break
        g = cv2.cvtColor(f, cv2.COLOR_BGR2GRAY)
        if mask is not None: g[mask] = 128
        cv2.imwrite(str(out / f"mav0/cam0/data/{int(t_cam[k])}.png"), g); rows.append(int(t_cam[k])); k += 1
    (out / "mav0/cam0/data.csv").write_text("#timestamp [ns],filename\n" + "".join(f"{t},{t}.png\n" for t in rows))
    (out / "times.txt").write_text("".join(f"{t}\n" for t in rows))
    ye = yaml.safe_load((ROOT / "configs/calibration/trackcam_imu_v001.yaml").read_text()); off = float(ye["offset_ms"]); Rci = np.asarray(ye["R_CI"], float)
    z = np.load(E / "imu_right.npz"); ti = fit_device_to_host(z["device_us"], z["host_ns"]).to_host_ns(z["device_us"]).astype(np.int64) + int(off * 1e6)
    o = np.argsort(ti); ti, gy, ac = ti[o], z["gyro"][o], z["acc"][o]; keep = np.r_[True, np.diff(ti) > 0]
    (out / "mav0/imu0/data.csv").write_text("#timestamp [ns],w_RS_S_x [rad s^-1],w_RS_S_y [rad s^-1],w_RS_S_z [rad s^-1],a_RS_S_x [m s^-2],a_RS_S_y [m s^-2],a_RS_S_z [m s^-2]\n"
                                             + "".join(f"{t},{w[0]:.9f},{w[1]:.9f},{w[2]:.9f},{x[0]:.9f},{x[1]:.9f},{x[2]:.9f}\n" for t, w, x in zip(ti[keep], gy[keep], ac[keep])))
    t_ci = np.asarray(json.loads((ROOT / a.lever_from / "board_lever.json").read_text())["t_CI_m"], float)
    T_CI = np.eye(4); T_CI[:3, :3] = Rci; T_CI[:3, 3] = t_ci; T_IC = np.linalg.inv(T_CI)            # ORB-SLAM3 IMU.T_b_c1 = camera -> body(IMU)
    yi = yaml.safe_load((ROOT / "configs/calibration/trackcam_fisheye_v001.yaml").read_text()); K = np.asarray(yi["K"], float).reshape(3, 3) / sc; D = yi["D"]
    yn = yaml.safe_load((ROOT / "configs/calibration/camera_imu_right_v002.yaml").read_text())["imu_noise"]
    w, h = 1920 // sc, 1080 // sc
    s = f"""%YAML:1.0
# trackcam fisheye + right UMI Teensy, generated by scripts/trackcam_orb3_export.py ({E.name}, variant {a.variant})
File.version: "1.0"
Camera.type: "KannalaBrandt8"
Camera1.fx: {K[0, 0]:.6f}
Camera1.fy: {K[1, 1]:.6f}
Camera1.cx: {K[0, 2]:.6f}
Camera1.cy: {K[1, 2]:.6f}
Camera1.k1: {D[0]:.8f}
Camera1.k2: {D[1]:.8f}
Camera1.k3: {D[2]:.8f}
Camera1.k4: {D[3]:.8f}
Camera.width: {w}
Camera.height: {h}
Camera.fps: 30
Camera.RGB: 0
IMU.T_b_c1: !!opencv-matrix
   rows: 4
   cols: 4
   dt: f
   data: [{", ".join(f"{v:.9f}" for v in T_IC.ravel())}]
IMU.InsertKFsWhenLost: 0
IMU.NoiseGyro: {yn["gyroscope_noise_density"] * NOISE_X:.6e}
IMU.NoiseAcc: {yn["accelerometer_noise_density"] * NOISE_X:.6e}
IMU.GyroWalk: {yn["gyroscope_random_walk"] * WALK_X:.6e}
IMU.AccWalk: {yn["accelerometer_random_walk"] * WALK_X:.6e}
IMU.Frequency: 200.0
ORBextractor.nFeatures: {a.n_features}
ORBextractor.scaleFactor: 1.2
ORBextractor.nLevels: 8
ORBextractor.iniThFAST: 20
ORBextractor.minThFAST: 7
Viewer.KeyFrameSize: 0.05
Viewer.KeyFrameLineWidth: 1.0
Viewer.GraphLineWidth: 0.9
Viewer.PointSize: 2.0
Viewer.CameraSize: 0.08
Viewer.CameraLineWidth: 3.0
Viewer.ViewpointX: 0.0
Viewer.ViewpointY: -0.7
Viewer.ViewpointZ: -3.5
Viewer.ViewpointF: 500.0
"""
    (out / "settings.yaml").write_text(s)
    print(f"{out}: frames {len(rows)}, imu {int(keep.sum())}, offset {off} ms, t_CI {t_ci.tolist()}, |t| {np.linalg.norm(t_ci) * 100:.1f} cm")


if __name__ == "__main__":
    main()
